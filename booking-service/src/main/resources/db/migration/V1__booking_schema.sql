create table users (
    id bigint generated by default as identity primary key,
    username varchar(64) not null unique,
    password varchar(100) not null,
    role varchar(16) not null check (role in ('USER', 'ADMIN')),
    active boolean not null default true
);
create table bookings (
    id uuid primary key,
    user_id bigint not null references users(id),
    room_id bigint,
    hotel_id bigint,
    auto_select boolean not null,
    start_date date not null,
    end_date date not null,
    status varchar(16) not null check (status in ('PENDING', 'CONFIRMED', 'CANCELLED')),
    request_key varchar(128) not null,
    fingerprint varchar(64) not null,
    failure_code varchar(40),
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone not null,
    compensation_pending boolean not null default false,
    compensation_attempts integer not null default 0,
    next_compensation_at timestamp with time zone,
    cancellation_reason varchar(24),
    version bigint not null default 0,
    unique (user_id, request_key),
    check (start_date < end_date)
);
create index idx_booking_history on bookings(user_id, created_at, id);
create index idx_booking_pending on bookings(status, updated_at);
create index idx_booking_compensation on bookings(compensation_pending, next_compensation_at);
