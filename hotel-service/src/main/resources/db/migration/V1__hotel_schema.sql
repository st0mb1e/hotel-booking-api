create table hotels (
    id bigint generated by default as identity primary key,
    name varchar(120) not null,
    address varchar(300) not null,
    deleted boolean not null default false
);
create table rooms (
    id bigint generated by default as identity primary key,
    hotel_id bigint not null references hotels(id),
    number varchar(30) not null,
    available boolean not null default true,
    times_booked bigint not null default 0 check (times_booked >= 0),
    deleted boolean not null default false,
    version bigint not null default 0,
    unique (hotel_id, number)
);
create table room_reservations (
    booking_id uuid primary key,
    room_id bigint not null references rooms(id),
    start_date date,
    end_date date,
    status varchar(16) not null check (status in ('RESERVED', 'RELEASED')),
    release_reason varchar(24),
    created_at timestamp with time zone not null,
    check (status = 'RELEASED' or (start_date is not null and end_date is not null and start_date < end_date))
);
create index idx_reservation_calendar on room_reservations(room_id, status, start_date, end_date);
create index idx_rooms_recommend on rooms(available, deleted, times_booked, id);
